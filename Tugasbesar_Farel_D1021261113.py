import streamlit as st

# ==========================================
# APLIKASI PERHITUNGAN BIAYA LAUNDRY KILOAN
# ==========================================

st.set_page_config(
    page_title="Laundry Kiloan",
    page_icon="🧺",
    layout="centered"
)

# Fungsi reset
def reset():
    st.session_state.nim = ""
    st.session_state.berat = 1
    st.session_state.hasil = False

# Inisialisasi session state
if "hasil" not in st.session_state:
    st.session_state.hasil = False

if "nim" not in st.session_state:
    st.session_state.nim = ""

if "berat" not in st.session_state:
    st.session_state.berat = 1

# Judul aplikasi
st.title("🧺 Aplikasi Biaya Laundry Kiloan")
st.subheader("Perhitungan Biaya Laundry")


st.divider()

# Input data
st.subheader("Masukkan Data Pelanggan")

nim = st.text_input(
    "Masukkan NIM (10 digit)",
    key="nim"
)

berat = st.number_input(
    "Berat Cucian (kg)",
    min_value=-100,
    max_value=1000,
    step=1,
    key="berat"
)

# Tombol
col1, col2 = st.columns(2)

with col1:
    hitung = st.button("🧮 Hitung", use_container_width=True)

with col2:
    st.button(
        "🔄 Reset",
        on_click=reset,
        use_container_width=True
    )

# Proses perhitungan
if hitung:

    st.session_state.hasil = False

    # Validasi NIM
    if not nim.isdigit() or len(nim) != 10:
        st.error("NIM harus terdiri tepat dari 10 digit angka!")

    # Validasi berat cucian
    elif berat <= 0 or berat != int(berat):
        st.error("Berat cucian harus berupa bilangan bulat positif lebih dari 0!")

    else:
        # Menghitung jumlah digit genap
        digit_genap = sum(
            1 for angka in nim if int(angka) % 2 == 0
        )

        # Menghitung tarif per kg
        digit_terakhir = int(nim[-1])
        tarif = 5000 + (digit_terakhir * 500)

        # Menghitung diskon
        persen_diskon = digit_genap * 1

        # Menghitung biaya normal
        biaya_normal = int(berat) * tarif

        # Menghitung potongan
        potongan = biaya_normal * persen_diskon / 100

        # Menghitung total bayar
        total_bayar = biaya_normal - potongan

        st.session_state.hasil = True

        # Menampilkan hasil
        st.divider()
        st.subheader("📋 Hasil Perhitungan")

        st.success("Data berhasil dihitung!")


        st.write(f"**Berat Cucian:** {int(berat)} kg")
        st.write(f"**Digit Genap:** {digit_genap}")

        st.divider()

        st.write(
            f"**Tarif per kg:** Rp {tarif:,.0f}".replace(",", ".")
        )

        st.write(
            f"**Persen Diskon:** {persen_diskon}%"
        )

        st.write(
            f"**Biaya Normal:** Rp {biaya_normal:,.0f}".replace(",", ".")
        )

        st.write(
            f"**Potongan:** Rp {potongan:,.0f}".replace(",", ".")
        )

        st.divider()

        st.success(
            f"### Total Bayar: Rp {total_bayar:,.0f}".replace(",", ".")
        )

st.divider()

st.caption(
    "Aplikasi Tugas Besar Python dan Streamlit "

)